import time
import random

class Lesson:
    def __init__(self, title, sections):
        self.title = title
        self.sections = sections

    def display_menu(self):
        print(f"\n--- {self.title} ---")
        for idx, section in enumerate(self.sections):
            print(f"{idx + 1}. {section['title']}")
        print("5. Просмотреть всю лекцию")  # Добавлена опция для просмотра всей лекции
        print("0. Назад")

    def read_section(self, section):
        print(f"\n{section['title']}\n")
        lines = section['content']
        
        for line in lines:
            print(line)
            time.sleep(0.2)  # Задержка в 0.2 секунды между строками

        # После прочтения раздела, предложим тест
        if self.offer_test():
            return True  # Возврат к разделу
        return False  # Не возвращаемся, если тест пройден

    def offer_test(self):
        questions = [
            {
                "question": "Что такое область видимости имени?",
                "options": ["a) Область, где имя может использоваться", "b) Область, где имя не может использоваться", "c) Область, где имя определено"],
                "answer": "a"
            },
            {
                "question": "Что такое функция?",
                "options": ["a) Поименованная часть программы", "b) Переменная", "c) Объект"],
                "answer": "a"
            },
            {
                "question": "Что такое структура?",
                "options": ["a) Совокупность элементов одного типа", "b) Совокупность элементов произвольных типов", "c) Стандартная библиотека"],
                "answer": "b"
            }
        ]
        
        random.shuffle(questions)  # Перемешиваем вопросы
        score = 0

        print("\n--- Тест по разделу ---")
        for i, q in enumerate(questions[:3]):  # Берем только 3 вопроса
            print(f"{i + 1}. {q['question']}")
            for option in q['options']:
                print(option)
            answer = input("Ваш ответ (a/b/c): ").lower()
            if answer == q['answer']:
                print("Правильно!")
                score += 1
            else:
                print(f"Неправильно! Правильный ответ: {q['answer']}")

        print(f"\nВы ответили правильно на {score} из 3 вопросов.")
        
        if score < 2:  # Если меньше 2 правильных ответов
            print("Вы не прошли тест. Хотите вернуться к последнему пройденному разделу? (да/нет)")
            if input().lower() == 'да':
                return True  # Возврат к разделу
        return False  # Не возвращаемся, если тест пройден

    def read_all(self):
        for section in self.sections:
            self.read_section(section)
